int32_t SpecctraDsnStreamReader::zzReaderRead(jrt::Array<char16_t>* cbuf, int32_t off,
                                              int32_t len) {
  // PORT NOTE: emulates InputStreamReader(in, UTF-8).read(cbuf, off, len). Malformed sequences are
  // replaced by U+FFFD (one per maximal invalid subpart, like Java's decoder). Java may return
  // fewer chars than requested; this reads until len chars are produced or the input ends, which
  // only changes buffer refill boundaries (not the scanned tokens).
  if (len <= 0) {
    return 0;
  }
  int32_t n = 0;
  char16_t* out = cbuf->data() + off;
  std::istream& in = *zzReader;
  auto nextByte = [&in]() -> int32_t {
    int c = in.get();
    return c == std::char_traits<char>::eof() ? -1 : (c & 0xFF);
  };
  auto peekCont = [&in]() -> bool {
    int c = in.peek();
    return c != std::char_traits<char>::eof() && (c & 0xC0) == 0x80;
  };
  if (zzPendingLowSurrogate >= 0) {
    out[n++] = static_cast<char16_t>(zzPendingLowSurrogate);
    zzPendingLowSurrogate = -1;
  }
  while (n < len) {
    int32_t b0 = nextByte();
    if (b0 < 0) {
      break;
    }
    if (b0 < 0x80) {
      out[n++] = static_cast<char16_t>(b0);
      continue;
    }
    int32_t need;
    int32_t cp;
    int32_t minCp;
    if (b0 >= 0xC2 && b0 <= 0xDF) {
      need = 1;
      cp = b0 & 0x1F;
      minCp = 0x80;
    } else if (b0 >= 0xE0 && b0 <= 0xEF) {
      need = 2;
      cp = b0 & 0x0F;
      minCp = 0x800;
    } else if (b0 >= 0xF0 && b0 <= 0xF4) {
      need = 3;
      cp = b0 & 0x07;
      minCp = 0x10000;
    } else {
      out[n++] = u'\xFFFD';
      continue;
    }
    bool ok = true;
    for (int32_t k = 0; k < need; ++k) {
      if (!peekCont()) {
        ok = false;
        break;
      }
      int32_t b = in.peek() & 0xFF;
      // second byte range restrictions (overlongs, surrogates, > U+10FFFF)
      if (k == 0) {
        if ((b0 == 0xE0 && b < 0xA0) || (b0 == 0xED && b > 0x9F) || (b0 == 0xF0 && b < 0x90) ||
            (b0 == 0xF4 && b > 0x8F)) {
          ok = false;
          break;
        }
      }
      nextByte();
      cp = (cp << 6) | (b & 0x3F);
    }
    if (!ok || cp < minCp) {
      out[n++] = u'\xFFFD';
      continue;
    }
    if (cp < 0x10000) {
      out[n++] = static_cast<char16_t>(cp);
    } else {
      cp -= 0x10000;
      char16_t hi = static_cast<char16_t>(0xD800 + (cp >> 10));
      char16_t lo = static_cast<char16_t>(0xDC00 + (cp & 0x3FF));
      out[n++] = hi;
      if (n < len) {
        out[n++] = lo;
      } else {
        zzPendingLowSurrogate = lo;
      }
    }
  }
  if (n == 0) {
    return -1;
  }
  return n;
}

std::string SpecctraDsnStreamReader::utf16ToUtf8(const char16_t* text, int32_t length) {
  std::string result;
  result.reserve(static_cast<std::size_t>(length));
  for (int32_t i = 0; i < length; ++i) {
    uint32_t c = text[i];
    if (c >= 0xD800 && c <= 0xDBFF && i + 1 < length && text[i + 1] >= 0xDC00 &&
        text[i + 1] <= 0xDFFF) {
      c = 0x10000 + ((c - 0xD800) << 10) + (static_cast<uint32_t>(text[i + 1]) - 0xDC00);
      ++i;
    } else if (c >= 0xD800 && c <= 0xDFFF) {
      // PORT NOTE: lone surrogate; Java's String -> UTF-8 encoding writes '?'.
      result += '?';
      continue;
    }
    if (c < 0x80) {
      result += static_cast<char>(c);
    } else if (c < 0x800) {
      result += static_cast<char>(0xC0 | (c >> 6));
      result += static_cast<char>(0x80 | (c & 0x3F));
    } else if (c < 0x10000) {
      result += static_cast<char>(0xE0 | (c >> 12));
      result += static_cast<char>(0x80 | ((c >> 6) & 0x3F));
      result += static_cast<char>(0x80 | (c & 0x3F));
    } else {
      result += static_cast<char>(0xF0 | (c >> 18));
      result += static_cast<char>(0x80 | ((c >> 12) & 0x3F));
      result += static_cast<char>(0x80 | ((c >> 6) & 0x3F));
      result += static_cast<char>(0x80 | (c & 0x3F));
    }
  }
  return result;
}

std::optional<double> SpecctraDsnStreamReader::parseNumberFormatUS(const std::string& s) {
  // PORT NOTE: emulates NumberFormat.getInstance(Locale.US).parse(s).doubleValue()
  // (DecimalFormat with positive prefix "", negative prefix "-", ',' grouping, '.' decimal point).
  // The Java result is a Long when the value is integral and fits, else a Double; both are only
  // used through doubleValue(), and both conversions are correctly rounded, so parsing the
  // collected digits with from_chars gives the identical double. Only ASCII digits are accepted
  // (Java's Character.digit also accepts other Unicode decimal digits).
  std::size_t pos = 0;
  // NaN symbol is checked first
  if (s.compare(0, 3, "NaN") == 0) {
    return jrt::Double::NaN;
  }
  bool negative = false;
  if (pos < s.size() && s[pos] == '-') {
    negative = true;
    ++pos;
  }
  // infinity symbol U+221E
  if (s.compare(pos, 3, "\xE2\x88\x9E") == 0) {
    return negative ? jrt::Double::NEGATIVE_INFINITY : jrt::Double::POSITIVE_INFINITY;
  }
  std::string digits;
  bool sawDigit = false;
  bool sawDecimal = false;
  for (; pos < s.size(); ++pos) {
    char ch = s[pos];
    if (ch >= '0' && ch <= '9') {
      sawDigit = true;
      digits += ch;
    } else if (ch == '.') {
      if (sawDecimal) {
        break;
      }
      sawDecimal = true;
      digits += '.';
    } else if (ch == ',') {
      if (sawDecimal) {
        break;
      }
      // grouping separator: skipped
    } else {
      break;
    }
  }
  if (!sawDigit) {
    return std::nullopt;
  }
  std::string number = (negative ? "-" : "") + digits;
  double value = 0.0;
  auto res = std::from_chars(number.data(), number.data() + number.size(), value);
  if (res.ec == std::errc::result_out_of_range) {
    // overflow -> infinity, underflow -> (signed) zero, like Double.parseDouble
    bool tiny = false;
    // determine magnitude: any non-zero digit before '.' means overflow
    for (char c : digits) {
      if (c == '.') {
        tiny = true;
        break;
      }
      if (c != '0') {
        break;
      }
    }
    if (tiny) {
      return negative ? -0.0 : 0.0;
    }
    return negative ? jrt::Double::NEGATIVE_INFINITY : jrt::Double::POSITIVE_INFINITY;
  }
  return value;
}

