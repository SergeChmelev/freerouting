JNumber* SpecctraDsnStreamReader::readFloatingToken() {
  bool hasExp = false;
  for (int32_t i = zzStartRead; i < zzMarkedPos; i++) {
    char16_t c = (*zzBuffer)[i];
    if (c == u'e' || c == u'E') {
      hasExp = true;
      break;
    }
  }
  if (hasExp) {
    while (true) {
      if (zzMarkedPos >= zzEndRead) {
        zzCurrentPos = zzMarkedPos;
        if (zzAtEOF || zzRefill()) {
          break;
        }
      }
      char16_t c = (*zzBuffer)[zzMarkedPos];
      if (c < u'0' || c > u'9') {
        break;
      }
      zzMarkedPos++;
    }
  }
  std::string literal = utf16ToUtf8(zzBuffer->data() + zzStartRead, zzMarkedPos - zzStartRead);
  if (exactNumbers) {
    return new (jrt::kOp) JBigDecimal(jrt::BigDecimal(literal));
  }
  return new (jrt::kOp) JDouble(jrt::Double::parseDouble(literal));
}

bool SpecctraDsnStreamReader::hasStringChar(int32_t offset) {
  while (zzMarkedPos + offset >= zzEndRead) {
    if (zzAtEOF) {
      return false;
    }
    int32_t currentOffset = zzCurrentPos - zzStartRead;
    zzCurrentPos = jrt::Math::max(zzCurrentPos, zzMarkedPos + offset);
    bool endOfInput;
    try {
      endOfInput = zzRefill();
    } catch (const jrt::IOException& e) {
      return false;
    }
    zzCurrentPos = zzStartRead + currentOffset;
    if (endOfInput) {
      return false;
    }
  }
  return true;
}

std::string SpecctraDsnStreamReader::nextString(bool ignoreNewline, char16_t leading) {
  stringBuffer.clear();
  int32_t i = 0;
  while (hasStringChar(i)) {
    char16_t c = (*zzBuffer)[zzMarkedPos + i];
    if (!(c == u' ' || c == u'\t' || c == u'\b' || c == leading ||
          (ignoreNewline && (c == u'\n' || c == u'\r')))) {
      break;
    }
    i++;
  }

  bool quoted = hasStringChar(i) && (*zzBuffer)[zzMarkedPos + i] == u'"';
  if (quoted) {
    i++;
  }
  while (hasStringChar(i)) {
    char16_t c = (*zzBuffer)[zzMarkedPos + i];
    if (quoted ? (c == u'\n' || c == u'\r' || c == u'"')
               : (c == u' ' || c == u'\t' || c == u'\b' || c == u'\n' || c == u'\r' ||
                  c == u'(' || c == u')' || c == leading)) {
      break;
    }
    stringBuffer.push_back(c);
    i++;
  }
  if (quoted && hasStringChar(i)) {
    i++; // the closing quote
  }

  if (i > 0) {
    zzStartRead += i - 1;
    zzCurrentPos += i - 1;
    zzMarkedPos += i;
    zzLexicalState = YYINITIAL;

    if (((*zzBuffer)[zzMarkedPos - 1] == 40) || ((*zzBuffer)[zzMarkedPos - 1] == 41)) {
      // if the string ended with brackets, we need to step back one character, because we need
      // that bracket as the next token
      zzStartRead--;
      zzCurrentPos--;
      zzMarkedPos--;
    }
  }

  return utf16ToUtf8(stringBuffer.data(), static_cast<int32_t>(stringBuffer.size()));
}

jrt::Array<std::string>* SpecctraDsnStreamReader::nextStringList(char separator) {
  auto* result = new jrt::LinkedList<std::string>();

  // Every string list must have at least one item, but the first item can be empty. In this case
  // we ignore that and continue reading the next item.
  // This is extra step is also needed to handle the bug KiCad 8 introduced in the netlist
  // definition, when it started the list of nets with a "" string.
  std::string firstString = nextString(true, static_cast<char16_t>(static_cast<unsigned char>(separator)));
  if (firstString.length() > 0) {
    result->add(firstString);
  }

  for (;;) {
    std::string nextString_ =
        nextString(true, static_cast<char16_t>(static_cast<unsigned char>(separator)));
    if (nextString_.length() == 0) {
      break;
    }

    result->add(nextString_);
  }

  zzStartRead = zzMarkedPos - 1;
  zzCurrentPos = zzMarkedPos - 1;

  auto* arr = new jrt::Array<std::string>(result->size());
  int32_t k = 0;
  for (const std::string& s : *result) {
    (*arr)[k++] = s;
  }
  return arr;
}

std::optional<double> SpecctraDsnStreamReader::nextDouble() {
  std::string s = nextString();

  if (jrt::contains(s, "e") || jrt::contains(s, "E")) {
    try {
      double value = jrt::Double::parseDouble(s);
      return jrt::Double::isFinite(value) ? std::optional<double>(value) : std::nullopt;
    } catch (const jrt::NumberFormatException&) {
      return std::nullopt;
    }
  }

  // PORT NOTE: NumberFormat nf (lazily created static) replaced by parseNumberFormatUS().
  return parseNumberFormatUS(s);
}

bool SpecctraDsnStreamReader::nextClosingBracket() {
  jrt::Object* nextToken_;
  try {
    nextToken_ = nextToken();
  } catch (const jrt::IOException& e) {
    FRLogger::error("Network.read_net_pins: IO error scanning file", &e);
    return false;
  }
  if (nextToken_ == nullptr) {
    FRLogger::warn("Network.read_net_pins: unexpected end of file");
    return false;
  }
  if (nextToken_ != Keyword::CLOSED_BRACKET()) {
    // not end of scope
    FRLogger::warn("Network.read_net_pins: expected closed bracket is missing");
    return false;
  }

  return true;
}

