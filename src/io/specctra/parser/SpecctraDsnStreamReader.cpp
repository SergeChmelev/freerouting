void SpecctraDsnStreamReader::zzScanError(int32_t errorCode) {
  std::string message;
  if (errorCode >= 0 && errorCode < ZZ_ERROR_MSG()->length) {
    message = (*ZZ_ERROR_MSG())[errorCode];
  } else {
    message = (*ZZ_ERROR_MSG())[ZZ_UNKNOWN_ERROR];
  }

  throw jrt::Error(message);
}

void SpecctraDsnStreamReader::yypushback(int32_t number) {
  if (number > yylength()) {
    zzScanError(ZZ_PUSHBACK_2BIG);
  }

  zzMarkedPos -= number;
}

