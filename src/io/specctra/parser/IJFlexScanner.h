#pragma once

#include "fwd.h"
#include "jrt/jrt.h"

namespace fr::dsn {

// -------------------------------------------------------------------------------------------------
// PORT NOTE: scanner tokens. Java's IJFlexScanner.nextToken() returns Object: a Keyword instance,
// a java.lang.String, an Integer, a Double or (exact-number mode) a BigDecimal, or null at EOF.
// jrt has no boxed types, so the token boxes below stand in for them:
//   token instanceof String s       -> auto* s = jrt::fast_cast<JString>(token); s->value
//   token instanceof Integer i      -> auto* i = jrt::fast_cast<JInteger>(token); i->value
//   token instanceof Double d       -> auto* d = jrt::fast_cast<JDouble>(token); d->value
//   token instanceof Number n       -> auto* n = jrt::fast_cast<JNumber>(token); n->doubleValue()
//   token instanceof BigDecimal b   -> auto* b = jrt::fast_cast<JBigDecimal>(token); b->value
//   token == Keyword.X              -> token == Keyword::X()   (identity, as in Java)
// "..." + token uses jrt::str(token), which calls the toString() overrides below (Java format).
// -------------------------------------------------------------------------------------------------

/** Boxed java.lang.String token. */
class JString final : public virtual jrt::Object {
 public:
  explicit JString(std::string v) : value(std::move(v)) {}
  std::string value;

  bool equals(jrt::Object* o) override {
    auto* other = jrt::fast_cast<JString>(o);
    return other != nullptr && other->value == value;
  }
  int32_t hashCode() override { return jrt::stringHashCode(value); }
  std::string toString() override { return value; }
};

/** Boxed java.lang.Number token (abstract). */
class JNumber : public virtual jrt::Object {
 public:
  virtual int32_t intValue() = 0;
  virtual int64_t longValue() = 0;
  virtual double doubleValue() = 0;
};

/** Boxed java.lang.Integer token. */
class JInteger final : public JNumber {
 public:
  explicit JInteger(int32_t v) : value(v) {}
  int32_t value;

  int32_t intValue() override { return value; }
  int64_t longValue() override { return value; }
  double doubleValue() override { return static_cast<double>(value); }
  bool equals(jrt::Object* o) override {
    auto* other = jrt::fast_cast<JInteger>(o);
    return other != nullptr && other->value == value;
  }
  int32_t hashCode() override { return value; }
  std::string toString() override { return jrt::str(value); }
};

/** Boxed java.lang.Double token. */
class JDouble final : public JNumber {
 public:
  explicit JDouble(double v) : value(v) {}
  double value;

  int32_t intValue() override { return jrt::d2i(value); }
  int64_t longValue() override { return jrt::d2l(value); }
  double doubleValue() override { return value; }
  bool equals(jrt::Object* o) override {
    auto* other = jrt::fast_cast<JDouble>(o);
    return other != nullptr &&
           jrt::Double::doubleToLongBits(other->value) == jrt::Double::doubleToLongBits(value);
  }
  int32_t hashCode() override { return jrt::Double::hashCode(value); }
  std::string toString() override { return jrt::str(value); }
};

/** Boxed java.math.BigDecimal token (exact-number mode, SES reading). */
class JBigDecimal final : public JNumber {
 public:
  explicit JBigDecimal(jrt::BigDecimal v) : value(std::move(v)) {}
  jrt::BigDecimal value;

  // PORT NOTE: Java BigDecimal.intValue()/longValue() truncate the exact value; approximated via
  // the double value (only used for small magnitudes).
  int32_t intValue() override { return jrt::d2i(value.doubleValue()); }
  int64_t longValue() override { return jrt::d2l(value.doubleValue()); }
  double doubleValue() override { return value.doubleValue(); }
  bool equals(jrt::Object* o) override {
    auto* other = jrt::fast_cast<JBigDecimal>(o);
    return other != nullptr && other->value.scale() == value.scale() &&
           other->value.unscaledValue().equals(value.unscaledValue());
  }
  int32_t hashCode() override {
    return jrt::hashCombine(value.unscaledValue().hashCode(), value.scale());
  }
  // PORT NOTE: Java BigDecimal.toString() may use exponent notation; jrt only has toPlainString.
  std::string toString() override { return value.toString(); }
};

/** Interface for scanner generated by jflex. */
class IJFlexScanner : public virtual jrt::Object {
 public:
  /* Returns the current scope identifier. */
  virtual std::string getScopeIdentifier() = 0;

  /* Sets the current scope identifier. */
  virtual void setScopeIdentifier(const std::string& identifier) = 0;

  /** Reads the next token from the input file (null at end of file). Throws jrt::IOException. */
  virtual jrt::Object* nextToken() = 0;

  /** Reads the next token as a string from the input file. */
  virtual std::string nextString() = 0;

  virtual std::string nextString(bool ignoreNewline) = 0;

  virtual jrt::Array<std::string>* nextStringList() = 0;

  virtual jrt::Array<std::string>* nextStringList(char separator) = 0;

  /** Reads the next token as a double from the input file (Java Double, nullable). */
  virtual std::optional<double> nextDouble() = 0;

  /** PORT NOTE: Java returns Boolean but never null -> bool. */
  virtual bool nextClosingBracket() = 0;

  /** Starts a new state. */
  virtual void yybegin(int32_t newState) = 0;

  /**
   * Returns the text of the last token as written in the file. Keywords are matched regardless of
   * case, so this is the only way to tell {@code Signal} from {@code signal}.
   */
  virtual std::string yytext() = 0;
};

}  // namespace fr::dsn
