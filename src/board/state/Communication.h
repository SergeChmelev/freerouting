// Port of app.freerouting.board.state.Communication
#pragma once

#include "fwd.h"
#include "jrt/jrt.h"

namespace fr {

/** The write resolution of a Specctra file ("resolution <charName> <positiveInt>"). */
class Communication_SpecctraParserInfo_WriteResolution : public virtual jrt::Object {
 public:
  Communication_SpecctraParserInfo_WriteResolution(const std::string& charName,
                                                   int32_t positiveInt)
      : charName(charName), positiveInt(positiveInt) {}

  const std::string charName;
  const int32_t positiveInt;
};

/** Information from the parser scope of a Specctra-dsn-file. */
class Communication_SpecctraParserInfo : public virtual jrt::Object {
 public:
  Communication_SpecctraParserInfo(
      const std::string& stringQuote, const std::optional<std::string>& hostCad,
      const std::optional<std::string>& hostVersion,
      jrt::Collection<jrt::Array<std::string>*>* constants,
      Communication_SpecctraParserInfo_WriteResolution* writeResolution,
      bool dsnFileGeneratedByHost)
      : stringQuote(stringQuote),
        hostCad(hostCad),
        hostVersion(hostVersion),
        constants(constants),
        writeResolution(writeResolution),
        dsnFileGeneratedByHost(dsnFileGeneratedByHost) {}

  /** Character used for quoting strings. */
  const std::string stringQuote;

  /** The host CAD system (null if unknown). */
  const std::optional<std::string> hostCad;
  /** The host CAD version (null if unknown). */
  const std::optional<std::string> hostVersion;
  /** The constants of the dsn file (pairs name, value); may be null. */
  jrt::Collection<jrt::Array<std::string>*>* constants;  // final
  /** The write resolution, or null. */
  Communication_SpecctraParserInfo_WriteResolution* writeResolution;  // final
  /** True, if the dsn file was generated by the host system. */
  const bool dsnFileGeneratedByHost;
};

/** Communication information to host systems or host design formats. */
class Communication : public virtual jrt::Object {
 public:
  // PORT NOTE (board deepCopy hook): copy with a deep-copied idGenerator (continues issuing the same
  // ids) and observers = nullptr; other fields copied by value.
  Communication* copyForBoard();
  /** Creates a new instance of BoardCommunication. */
  Communication(Unit unit, int32_t resolution, Communication_SpecctraParserInfo* specctraParserInfo,
                io::CoordinateTransform* coordinateTransform, IdGenerator* idGenerator,
                BoardObservers* observers)
      : coordinateTransform(coordinateTransform),
        unit(unit),
        resolution(resolution),
        specctraParserInfo(specctraParserInfo),
        idGenerator(idGenerator),
        observers(observers) {}

  /**
   * Creates a new instance with default values (MIL, resolution 1, quote "\"", identity
   * transform, a new ItemIdGenerator and a BoardObserverAdaptor).
   */
  Communication();

  /** Returns true if the host CAD is Fusion / CadSoft / Eagle. */
  bool hostCadIsFusion();

  /** Returns true if the host CAD is KiCad. */
  bool hostCadIsKiCad();

  /** Returns true if the host CAD is KiCad with major version <= 5. */
  bool hostIsOldKicad();

  /** Returns true if a host CAD is known. */
  bool hostCadExists();

  /** Returns the resolution scaled to the input unit. */
  double getResolution(Unit unit);

  /** Converts a physical value in unit to board coordinates. */
  double physicalToBoard(double value, Unit unit);

  /** For coordinate transforms between the dsn file and the board. */
  io::CoordinateTransform* coordinateTransform;  // final

  /** For coordinate transforms to a dsn-file. */
  const Unit unit;

  /** The resolution (1 / unit) used for coordinate transforms to a dsn file. */
  const int32_t resolution;

  Communication_SpecctraParserInfo* specctraParserInfo;  // final
  IdGenerator* idGenerator;                              // final
  /** Board observers (transient; reset to a BoardObserverAdaptor on deserialization in Java). */
  BoardObservers* observers;
};

}  // namespace fr
