// Generates the Java -> C++ class map and src/fwd.h for the port.
// usage: node tools/gen_classmap.js   (run from repo root)
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const JAVA = path.join(ROOT, 'upstream/src/main/java');
const classes = fs.readFileSync(path.join(__dirname, 'classes.txt'), 'utf8').split(/\r?\n/).filter(Boolean);

function nsFor(pkg) {
  if (pkg.startsWith('app.freerouting.io.specctra')) return 'fr::dsn';
  if (pkg === 'app.freerouting.io') return 'fr::io';
  return 'fr';
}
function relDir(pkg) {
  return pkg.replace(/^app\.freerouting\.?/, '').replace(/\./g, '/');
}

// Strip comments, string and char literals (keep length-insensitive structure).
function strip(src) {
  let out = '';
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i], d = src[i + 1];
    if (c === '/' && d === '/') { while (i < n && src[i] !== '\n') i++; continue; }
    if (c === '/' && d === '*') { i += 2; while (i < n && !(src[i] === '*' && src[i + 1] === '/')) i++; i += 2; continue; }
    if (c === '"' && src.startsWith('"""', i)) { i += 3; while (i < n && !src.startsWith('"""', i)) i++; i += 3; out += '""'; continue; }
    if (c === '"') { i++; while (i < n && src[i] !== '"') { if (src[i] === '\\') i++; i++; } i++; out += '""'; continue; }
    if (c === "'") { i++; while (i < n && src[i] !== "'") { if (src[i] === '\\') i++; i++; } i++; out += "' '"; continue; }
    out += c; i++;
  }
  return out;
}

const entries = [];  // {java, cpp, ns, kind, header, generic, outer}
for (const fq of classes) {
  const file = path.join(JAVA, fq.replace(/\./g, '/') + '.java');
  const src = strip(fs.readFileSync(file, 'utf8'));
  const pkg = fq.substring(0, fq.lastIndexOf('.'));
  const ns = nsFor(pkg);
  const header = relDir(pkg) + '/' + fq.substring(fq.lastIndexOf('.') + 1) + '.h';
  const re = /\b(class|interface|enum|record)\s+([A-Z]\w*)\s*(<[^{(]*?>)?/g;
  // Track braces: stack of {name, depth}
  const decls = [];
  let m;
  while ((m = re.exec(src))) {
    const before = src.substring(Math.max(0, m.index - 1), m.index);
    if (before === '.' || before === '@') continue;  // Foo.class, @interface
    decls.push({ kind: m[1], name: m[2], generic: m[3] || '', pos: m.index });
  }
  // Compute brace depth at each position, and type body open positions.
  const typeStack = [];  // {name, depth}
  let depth = 0;
  let di = 0;
  const pendingOpen = [];
  for (let i = 0; i < src.length; i++) {
    while (di < decls.length && decls[di].pos === i) {
      const d = decls[di++];
      d.outer = typeStack.length ? typeStack[typeStack.length - 1].cpp : null;
      d.cpp = d.outer ? d.outer + '_' + d.name : d.name;
      pendingOpen.push(d);
    }
    const c = src[i];
    if (c === '{') {
      depth++;
      if (pendingOpen.length) {
        const d = pendingOpen.shift();
        typeStack.push({ cpp: d.cpp, depth });
        // any other pending (shouldn't happen) are dropped
        pendingOpen.length = 0;
      }
    } else if (c === '}') {
      if (typeStack.length && typeStack[typeStack.length - 1].depth === depth) typeStack.pop();
      depth--;
    }
  }
  for (const d of decls) {
    if (!d.cpp) continue;
    const javaName = d.outer ? fq + '.' + d.cpp.split('_').slice(1).join('.') : fq;
    entries.push({
      java: d.outer ? fq + d.cpp.substring(d.cpp.indexOf('_')).replace(/_/g, '.') : fq,
      cpp: d.cpp, ns, kind: d.kind, header, generic: d.generic.replace(/\s+/g, ' ').trim(),
      nested: !!d.outer,
    });
  }
}

// Template parameter list from a Java generic declaration like <T extends Foo, U>
function templateParams(g) {
  if (!g) return null;
  let inner = g.slice(1, -1);
  const names = [];
  let lvl = 0, cur = '';
  for (const ch of inner) {
    if (ch === '<') lvl++;
    if (ch === '>') lvl--;
    if (ch === ',' && lvl === 0) { names.push(cur); cur = ''; } else cur += ch;
  }
  names.push(cur);
  return names.map(s => s.trim().split(/\s+/)[0]).filter(Boolean);
}

// fwd.h
const byNs = new Map();
for (const e of entries) {
  if (!byNs.has(e.ns)) byNs.set(e.ns, []);
  byNs.get(e.ns).push(e);
}
let fwd = '// GENERATED by tools/gen_classmap.js - do not edit.\n' +
  '// Forward declarations of every ported type. Nested Java types are hoisted to namespace\n' +
  '// scope as Outer_Inner. Enums are declared with an explicit int32_t underlying type, so\n' +
  '// their definitions MUST also be `enum class Name : int32_t { ... }`.\n' +
  '#pragma once\n\n#include <cstdint>\n\n';
for (const [ns, list] of [...byNs].sort()) {
  fwd += `namespace ${ns} {\n`;
  for (const e of list.sort((a, b) => a.cpp.localeCompare(b.cpp))) {
    const tp = templateParams(e.generic);
    if (e.kind === 'enum') fwd += `enum class ${e.cpp} : int32_t;\n`;
    else if (tp) fwd += `template <${tp.map(t => 'class ' + t).join(', ')}>\nclass ${e.cpp};\n`;
    else fwd += `class ${e.cpp};\n`;
  }
  fwd += `}  // namespace ${ns}\n\n`;
}
fs.writeFileSync(path.join(ROOT, 'src/fwd.h'), fwd);

// class map (TSV): java_fqn  cpp_qualified_name  kind  header  generic
let map = '# java_fqn\tcpp_name\tkind\theader\tgeneric\n';
for (const e of entries) map += `${e.java}\t${e.ns}::${e.cpp}\t${e.kind}\t${e.header}\t${e.generic}\n`;
fs.writeFileSync(path.join(ROOT, 'tools/classmap.tsv'), map);
console.log(`${entries.length} types (${entries.filter(e => e.nested).length} nested), ` +
  `${entries.filter(e => e.kind === 'enum').length} enums, ${entries.filter(e => e.generic).length} generic`);
// Detect duplicate C++ names within a namespace
const seen = new Map();
for (const e of entries) {
  const k = e.ns + '::' + e.cpp;
  if (seen.has(k)) console.log('DUPLICATE', k, seen.get(k), e.java);
  seen.set(k, e.java);
}
